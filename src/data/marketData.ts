// Helper to generate realistic candlestick data for any asset and timeframe
export function generateCandles(basePrice: number, count: number = 30, timeframe: string = '1D'): CandleData[] {
  const candles: CandleData[] = [];
  let currentClose = basePrice * 0.96;
  const now = new Date();

  for (let i = count; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 3600 * 1000 * (timeframe === '1D' ? 0.5 : timeframe === '5D' ? 2 : 24));
    const volatility = basePrice * 0.012;
    const change = (Math.random() - 0.48) * volatility;
    const open = currentClose;
    const close = Math.max(open + change, basePrice * 0.5);
    const high = Math.max(open, close) + Math.random() * volatility * 0.6;
    const low = Math.min(open, close) - Math.random() * volatility * 0.6;
    const volume = Math.floor(Math.random() * 800000 + 200000);

    const timeStr = timeframe === '1D' 
      ? time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
      : time.toLocaleDateString([], { month: 'short', day: 'numeric' });

    candles.push({
      time: timeStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume
    });

    currentClose = close;
  }

  // Ensure the last candle close matches current market price closely
  if (candles.length > 0) {
    const last = candles[candles.length - 1];
    last.close = basePrice;
    last.high = Math.max(last.high, basePrice);
    last.low = Math.min(last.low, basePrice);
  }

  return candles;
}
